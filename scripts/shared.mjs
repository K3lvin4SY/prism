#!/usr/bin/env node
/**
 * Copies the files in scripts/shared into every Prism extension's src/client (src for a theme), with a header
 * saying where they come from. Edit them here, then run this.
 *
 *   node scripts/shared.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, 'scripts', 'shared');

for (const extension of readdirSync(root).filter((name) => name.startsWith('prism-'))) {
    // A theme keeps its code straight in src.
    const client = [join(root, extension, 'src', 'client'), join(root, extension, 'src')].find((dir) => existsSync(dir));
    if (!client) continue;

    for (const file of readdirSync(shared)) {
        const source = readFileSync(join(shared, file), 'utf8');
        writeFileSync(join(client, file), `// Generated by scripts/shared.mjs from scripts/shared/${file}. Do not edit.\n${source}`);
    }
    console.log(`${extension}: ${readdirSync(shared).join(', ')}`);
}

#!/usr/bin/env node
/**
 * Writes src/client/icons.tsx in every Prism extension: a `NamedIcon` that takes the panel's lucide
 * names and draws the Tabler icon for each, from scripts/tabler-icons.json. Each extension gets the
 * icons it names in its source and manifest; Prism Layout and Prism Core draw icons named by
 * other extensions (navigation, settings) and get them all. Names without a Tabler icon fall back to
 * the panel's own set.
 *
 *   node scripts/icons.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const map = JSON.parse(readFileSync(join(root, 'scripts', 'tabler-icons.json'), 'utf8'));
const EVERY = new Set(['prism-layout', 'prism-core']);

const walk = (dir) =>
    readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : walk(path);

        return /\.(tsx?|json)$/.test(entry.name) && entry.name !== 'icons.tsx' ? [path] : [];
    });

for (const extension of readdirSync(root).filter((name) => name.startsWith('prism-'))) {
    const client = join(root, extension, 'src', 'client');
    if (!existsSync(client)) continue;

    const names = new Set();
    if (EVERY.has(extension)) Object.keys(map).forEach((name) => names.add(name));
    else {
        for (const file of [...walk(join(root, extension, 'src')), join(root, extension, 'extension.json')]) {
            for (const match of readFileSync(file, 'utf8').matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) {
                if (map[match[1]]) names.add(match[1]);
            }
        }
    }

    const used = [...names].sort();
    const components = [...new Set(used.map((name) => map[name]))].sort();
    const source = `// Generated by scripts/icons.mjs from scripts/tabler-icons.json. Do not edit.
import { NamedIcon as PanelIcon, type NamedIconProps } from '@pterodactyl/sdk';
import { ${components.join(', ')}, type TablerIcon } from '@tabler/icons-react';

const ICONS: Record<string, TablerIcon> = {
${used.map((name) => `    '${name}': ${map[name]},`).join('\n')}
};

/** A lucide icon name drawn as its Tabler icon; a name without one is drawn from the panel's set. */
export function NamedIcon({ name, size = 24, strokeWidth, absoluteStrokeWidth: _absolute, fallback, ...rest }: NamedIconProps) {
    const Tabler = ICONS[name];
    if (!Tabler) return <PanelIcon name={name} size={size} strokeWidth={strokeWidth} fallback={fallback} {...rest} />;

    return <Tabler size={size} stroke={strokeWidth ?? 2} {...(rest as object)} />;
}
`;
    writeFileSync(join(client, 'icons.tsx'), source);
    console.log(`${extension}: ${used.length} icons`);
}
